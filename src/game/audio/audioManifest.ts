const PIXABAY = 'Pixabay'
const KENNEY = 'Kenney'
const PROJECT = 'Cosmic Mail project'

function pixabay(
  title: string,
  author: string,
  url: string,
  contentIdRisk: 'none' | 'registered',
) {
  return {
    provider: PIXABAY,
    title,
    author,
    url,
    contentIdRisk,
    consultedAt: '2026-11-10',
  } as const
}

function kenney(title: string, pack: string) {
  return {
    provider: KENNEY,
    title: `${title} (${pack})`,
    author: 'Kenney',
    url: `https://kenney.nl/assets/${pack}`,
    contentIdRisk: 'none',
    consultedAt: '2026-11-10',
  } as const
}

function original(title: string) {
  return {
    provider: PROJECT,
    title,
    author: 'Cosmic Mail audio design',
    url: 'scripts/generate-cosmic-audio.py',
    contentIdRisk: 'none',
    consultedAt: '2026-11-10',
  } as const
}

type AssetSeed = Omit<AudioAsset, 'id'>

function asset(
  src: string,
  category: AudioAsset['category'],
  bus: AudioAsset['bus'],
  volume: number,
  loop: boolean,
  priority: number,
  license: AudioAsset['license'],
  source: AudioAsset['source'],
  tags: readonly string[] = [],
): AssetSeed {
  return { src, category, bus, volume, loop, priority, license, source, tags }
}

