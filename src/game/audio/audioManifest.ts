type AssetMap<T extends Record<string, AssetSeed>> = {
  [K in keyof T]: AudioAsset & { id: K }
}

function buildAssetMap<T extends Record<string, AssetSeed>>(
  seeds: T,
): AssetMap<T> {
  const map = {} as AssetMap<T>
  for (const [id, seed] of Object.entries(seeds)) {
    ;(map as Record<string, AudioAsset>)[id] = { id, ...seed }
  }
  return map
}

export const AUDIO_ASSETS = buildAssetMap(AUDIO_ASSET_SEEDS)

export type AudioAssetId = keyof typeof AUDIO_ASSETS

export function getAudioAsset(id: AudioAssetId): AudioAsset {
  return AUDIO_ASSETS[id]
}

export function audioUrl(asset: AudioAsset): string {
  const base =
    typeof import.meta !== 'undefined' && import.meta.env?.BASE_URL
      ? import.meta.env.BASE_URL
      : '/'
  const prefix = base.endsWith('/') ? base : `${base}/`
  return `${prefix}${asset.src.replace(/^\/+/, '')}`
}
